#!/usr/bin/env python3
"""Concise vectorization evidence for the write-up (no full dumps).

  python scripts/vec_evidence.py

Writes results/vec_evidence/:
  status_matrix.csv  every build x dtype x kernel: report verdict + width, and
                     what the main loop actually contains
  evidence.md        selected cases: the compiler's one-line verdict plus the
                     main loop (<= 15 instructions) of the disassembly
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import vecinfo as V  # noqa: E402

MAX_LINES = 15

CASES = [  # (build, symbol, why)
    ("gcc-scalar", "mul_f32", "Scalar baseline: one vmulss per element (same ISA, vectorizer off)."),
    ("gcc-default", "mul_f32", "Out-of-box -O3: SSE2 mulps on xmm, 4 lanes."),
    ("gcc-native256", "mul_f32", "-march=native: GCC's znver4 tuning prefers 256-bit ymm."),
    ("gcc-native512", "mul_f32", "-mprefer-vector-width=512: zmm, 16 lanes."),
    ("gcc-native512", "stencil_f32", "Stencil: three unaligned zmm loads (x[i-1], x[i], x[i+1]) and FMA contraction."),
    ("gcc-native512", "dot_simd_f32", "omp simd reduction, GCC: ONE zmm accumulator -> bound by 3-cycle vaddps latency."),
    ("clang-native512", "dot_simd_f32", "Same source, Clang: interleaves x4 -> four independent zmm accumulators."),
    ("gcc-native512", "dot_acc4_f32", "Source-level 4 accumulators: four zmm add chains under GCC too."),
    ("gcc-native512", "dot_plain_f32", "NEGATIVE: reported 'vectorized', but the reduction is in-order: 1 vmulps then 16 serial vaddss."),
    ("clang-native512", "dot_plain_f32", "NEGATIVE: Clang refuses (FP reassociation not allowed without fast-math)."),
    ("gcc-native512fm", "dot_plain_f32", "-ffast-math permits reassociation: a real packed reduction."),
    ("gcc-native512", "dot_s4_f32", "Constant stride 4: contiguous loads + vpermt2ps shuffles to pick every 4th element."),
    ("gcc-native512", "mul_gather_f32", "Indexed load: vgatherdps with a k-mask."),
    ("clang-native512", "mul_f32", "Clang default tail: vector body plus a scalar remainder loop."),
    ("clang-native512", "mul_pred_f32", "vectorize_predicate: masked {%k} loads/stores fold the tail, no scalar epilogue."),
]


def status_matrix():
    rows = []
    for b in V.builds():
        dis = V.disasm(b)
        for d in V.DTYPES:
            rep = V.report_summary(b, d)
            for k in V.kernels():
                st, wb, msgs = rep.get(k, ("missed", 0, []))
                lp = V.loop_stats(V.main_loop(dis[f"{k}_{d}"]))
                rows.append(dict(build=b, dtype=d, kernel=k, report=st, report_bits=wb * 8,
                                 loop_bits=lp.width, packed_fp=lp.packed_fp,
                                 int_simd=lp.int_simd, scalar_fp=lp.scalar_fp,
                                 gathers=lp.gathers, permutes=lp.permutes, masked=lp.masked,
                                 loop_insns=lp.n_insns, first_msg=(msgs[0][:160] if msgs else "")))
    return pd.DataFrame(rows)


def verdict(build, sym):
    k, d = sym.rsplit("_", 1)
    st, wb, msgs = V.report_summary(build, d).get(k, ("missed", 0, []))
    msg = msgs[0] if msgs else "(no remark on the main loop)"
    return msg.split("kernels_body.inc:")[-1] if "kernels_body.inc:" in msg else msg


def main():
    C.EVIDENCE.mkdir(parents=True, exist_ok=True)
    m = status_matrix()
    m.to_csv(C.EVIDENCE / "status_matrix.csv", index=False)
    out = ["# Vectorization evidence (concise)",
           "",
           "Generated by `scripts/vec_evidence.py` from the compiler reports "
           "(GCC `-fopt-info-vec-all`, Clang `-Rpass*=loop-vectorize`) and `objdump -d` of each "
           "kernel. Each case shows the compiler's verdict on the kernel's main loop and that loop's "
           f"instructions (truncated to {MAX_LINES}). Every build x dtype x kernel is in "
           "`status_matrix.csv`; `tests/test_vectorization.py` asserts that report and "
           "disassembly agree for all of them.", ""]
    for b, sym, why in CASES:
        body = V.main_loop(V.disasm(b)[sym]) or []
        st = V.loop_stats(body)
        out += [f"## `{sym}` - {b}", "", why, "",
                f"- report: `{verdict(b, sym)}`",
                f"- main loop: {st.n_insns} instructions, widest register {st.width or 'GPR'} bit, "
                f"packed FP {st.packed_fp}, scalar FP {st.scalar_fp}, int SIMD {st.int_simd}, "
                f"gathers {st.gathers}, permutes {st.permutes}, masked {st.masked}", "", "```asm"]
        for x in body[:MAX_LINES]:
            out.append(f"{x.mnem:<14}{x.ops}")
        if len(body) > MAX_LINES:
            out.append(f"... ({len(body) - MAX_LINES} more)")
        out += ["```", ""]
    (C.EVIDENCE / "evidence.md").write_text("\n".join(out))
    print(f"wrote {C.EVIDENCE / 'evidence.md'} and status_matrix.csv ({len(m)} rows)")


if __name__ == "__main__":
    main()
